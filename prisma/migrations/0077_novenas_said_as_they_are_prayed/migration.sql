-- Novena subtitles that say whom the novena is with, and when it is prayed, truly.
--
-- WHY: the subtitle under a novena's name in search named the saint the novena is linked
-- with as the one it prays to, and spelled the name from its web address. The Divine
-- Mercy Novena read "Nine-day novena to Saint Faustina Kowalska", though it prays to the
-- Lord whose mercy Saint Faustina made known; the novena of Our Lady of Guadalupe read "to
-- Saint Juan Diego"; Saint Alphonsus, who wrote the Christmas Novena, was named as the one
-- it is made to, and Saint Joseph as the one the Holy Family novena is made to. The names
-- built from addresses read "Saint Vincent De Paul" and "Saint Therese Of Lisieux". The
-- subtitle now names no saint at all, because the novena's own title already says whom it
-- honours, and a time that is not a date reads as the record writes it ("the nine days
-- before …", "any time of need") instead of "begins Any time"
-- (src/lib/content-shared/content-subtitle.ts).
--
-- Each new subtitle is what the application now writes for the curated novena, so the
-- worker's hygiene sweep, which keeps every subtitle in step with the application, finds
-- nothing to change. The checksum is of the title and the record, neither of which moves.
--
-- Deploy safety: one targeted update, no schema change. Safe to run again: a row is
-- changed only while it still holds exactly the old subtitle.
